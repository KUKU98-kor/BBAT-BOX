create extension if not exists pgcrypto with schema extensions;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (username ~ '^[a-z0-9_]{3,20}$'),
  full_name text not null check (char_length(full_name) between 1 and 20),
  nickname text not null check (char_length(nickname) between 1 and 16),
  status text not null default 'active' check (status in ('active', 'suspended')),
  is_platform_host boolean not null default false,
  must_change_password boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_username_lower_key
  on public.profiles (lower(username));

create unique index if not exists one_platform_host
  on public.profiles ((is_platform_host)) where is_platform_host;

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.team_members (
  team_id uuid not null references public.teams(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member'
    check (role in ('host', 'admin', 'manager', 'scorer', 'member')),
  status text not null default 'active'
    check (status in ('active', 'suspended')),
  joined_at timestamptz not null default now(),
  primary key (team_id, user_id)
);

create unique index if not exists one_host_per_team
  on public.team_members (team_id) where role = 'host';

create table if not exists public.team_invites (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.teams(id) on delete cascade,
  code_hash text not null unique,
  role text not null default 'member'
    check (role in ('host', 'admin', 'manager', 'scorer', 'member')),
  max_uses integer not null default 1 check (max_uses between 1 and 100),
  uses_count integer not null default 0 check (uses_count >= 0),
  expires_at timestamptz not null,
  active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.account_audit_log (
  id bigint generated by default as identity primary key,
  team_id uuid references public.teams(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  target_id uuid references public.profiles(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

